class EventPayload(BaseModel):
    """
    Payload for incoming events.

    Contains the actual message content and channel metadata.
    """

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "content": "Olá, gostaria de agendar uma consulta",
                "channel": "whatsapp",
                "user_id": "user-xyz-123",
                "metadata": {"phone": "+5511999999999", "name": "João Silva"},
            }
        }
    )

    content: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="Message content from the user",
        json_schema_extra={"example": "Olá, gostaria de agendar uma consulta"},
    )
    channel: str = Field(
        default="unknown",
        description="Communication channel (whatsapp, web, telegram, etc.)",
        json_schema_extra={"example": "whatsapp"},
    )
    user_id: Optional[str] = Field(
        default=None,
        description="External user identifier from the builder's system",
        json_schema_extra={"example": "user-xyz-123"},
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata from the channel",
        json_schema_extra={"example": {"phone": "+5511999999999"}},
    )
    language: str = Field(
        default="pt-BR",
        description="Response language code (pt-BR, en, es)",
        json_schema_extra={"example": "pt-BR"},
    )


class EventRequest(BaseModel):
    """
    Request model for event processing.

    This is the main input for the NeuroStack cognitive pipeline.
    """

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "tenant_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                "session_id": "b2c3d4e5-f6a7-8901-bcde-f12345678901",
                "event_type": "message.in",
                "payload": {
                    "content": "Olá, gostaria de agendar uma consulta",
                    "channel": "whatsapp",
                    "user_id": "user-xyz-123",
                },
            }
        }
    )

    tenant_id: UUID = Field(
        ...,
        description="Unique identifier for the tenant (clinic/builder)",
        json_schema_extra={"example": "a1b2c3d4-e5f6-7890-abcd-ef1234567890"},
    )
    session_id: UUID = Field(
        ...,
        description="Unique identifier for the conversation session",
        json_schema_extra={"example": "b2c3d4e5-f6a7-8901-bcde-f12345678901"},
    )
    event_type: EventType = Field(
        default=EventType.MESSAGE_IN,
        description="Type of event being processed",
        json_schema_extra={"example": "message.in"},
    )
    payload: EventPayload = Field(
        ...,
        description="Event payload with message content",
    )


