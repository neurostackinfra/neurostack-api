"""
NeuroStack API - Events Schemas
Contracts for event processing endpoints (/v1/events).
"""

from datetime import datetime
from enum import Enum
from typing import Any, Optional
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class EventType(str, Enum):
    """
    Types of events that can be processed.

    - message.in: Incoming message from user
    - message.out: Outgoing message to user (for logging)
    - session.start: New session started
    - session.end: Session ended
    - session.timeout: Session timed out
    - handoff.request: Human handoff requested
    - handoff.accept: Handoff accepted by human
    - handoff.complete: Human handoff completed
    - handoff.timeout: Handoff timed out
    - safety.trigger: Safety concern detected
    - safety.block: Response blocked for safety
    - srm.decision: SRM made a decision
    - state.patch: State was updated
    - funnel.transition: Funnel stage changed
    - rag.query: RAG query executed
    - rag.result: RAG results retrieved
    - policy.applied: Policy rules applied
    - policy.violation: Policy violation detected
    - prompt.generated: Prompt generated by prompt engine
    - error: Error occurred
    - warning: Warning raised
    """

    MESSAGE_IN = "message.in"
    MESSAGE_OUT = "message.out"
    SESSION_START = "session.start"
    SESSION_END = "session.end"
    SESSION_TIMEOUT = "session.timeout"
    HANDOFF_REQUEST = "handoff.request"
    HANDOFF_ACCEPT = "handoff.accept"
    HANDOFF_COMPLETE = "handoff.complete"
    HANDOFF_TIMEOUT = "handoff.timeout"
    SAFETY_TRIGGER = "safety.trigger"
    SAFETY_BLOCK = "safety.block"
    SRM_DECISION = "srm.decision"
    STATE_PATCH = "state.patch"
    FUNNEL_TRANSITION = "funnel.transition"
    RAG_QUERY = "rag.query"
    RAG_RESULT = "rag.result"
    POLICY_APPLIED = "policy.applied"
    POLICY_VIOLATION = "policy.violation"
    PROMPT_GENERATED = "prompt.generated"
    # CRM integration (doc MVP v0.5)
    NS_FUNNEL_STAGE_CHANGED = "ns.funnel_stage_changed"
    NS_HANDOFF_CREATED = "ns.handoff_created"
    ERROR = "error"
    WARNING = "warning"


class FlowMode(str, Enum):
    """
    Flow modes that determine how the response is generated.

    - normal: Standard conversational flow
    - rag: Knowledge retrieval flow (queries vector DB)
    - safety: Safety-constrained response mode
    - handoff: Human handoff preparation mode
    """

    NORMAL = "normal"
    RAG = "rag"
    SAFETY = "safety"
    HANDOFF = "handoff"


class IntentCategory(str, Enum):
    """
    High-level intent categories for classification.
    """

    SCHEDULING = "scheduling"
    QUESTION = "question"
    COMPLAINT = "complaint"
    GREETING = "greeting"
    FAREWELL = "farewell"
    CONFIRMATION = "confirmation"
    CANCELLATION = "cancellation"
    INFORMATION = "information"
    UNKNOWN = "unknown"


class SafetyCategory(str, Enum):
    """
    Safety concern categories.
    """

    CLINICAL_RISK = "clinical_risk"
    LEGAL_RISK = "legal_risk"
    CONDUCT_RISK = "conduct_risk"
    NONE = "none"


