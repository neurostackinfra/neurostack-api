"""
NeuroStack - Event Model
Append-only event store for cognitive events and decisions.
"""

from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING, Any, Optional
from uuid import UUID, uuid4

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, String, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.interaction_context import InteractionOrigin
from src.models.base import Base

if TYPE_CHECKING:
    from src.models.session import Session
    from src.models.tenant import Tenant


class EventType(str, Enum):
    """
    Types of events stored in the Event Store.

    Events are append-only and immutable once created.
    They provide a complete audit trail of all cognitive activity.
    """

    # Message Events
    MESSAGE_IN = "message.in"  # User message received
    MESSAGE_OUT = "message.out"  # Assistant message sent

    # Session Lifecycle
    SESSION_START = "session.start"  # New session created
    SESSION_END = "session.end"  # Session ended
    SESSION_TIMEOUT = "session.timeout"  # Session timed out

    # Cognitive Events
    SRM_DECISION = "srm.decision"  # SRM made a decision
    STATE_PATCH = "state.patch"  # State was updated
    FUNNEL_TRANSITION = "funnel.transition"  # Funnel stage changed

    # Safety Events
    SAFETY_TRIGGER = "safety.trigger"  # Safety concern detected
    SAFETY_BLOCK = "safety.block"  # Response blocked for safety

    # Handoff Events
    HANDOFF_REQUEST = "handoff.request"  # Handoff requested
    HANDOFF_ACCEPT = "handoff.accept"  # Handoff accepted by human
    HANDOFF_COMPLETE = "handoff.complete"  # Handoff completed
    HANDOFF_TIMEOUT = "handoff.timeout"  # Handoff timed out

    # RAG Events
    RAG_QUERY = "rag.query"  # RAG query executed
    RAG_RESULT = "rag.result"  # RAG results retrieved

    # Policy Events
    POLICY_APPLIED = "policy.applied"  # Policy rules applied
    POLICY_VIOLATION = "policy.violation"  # Policy violation detected

    # Prompt Events
    PROMPT_GENERATED = "prompt.generated"  # Prompt generated by prompt engine

    # CRM Integration Events (doc MVP v0.5 - contrato para integradores)
    NS_ATENDIMENTO_TIPO_SET = "ns.atendimento_tipo_set"
    NS_FUNNEL_STAGE_CHANGED = "ns.funnel_stage_changed"  # Etapa do funil alterada
    NS_HANDOFF_CREATED = "ns.handoff_created"  # Handoff criado

    # System Events
    ERROR = "error"  # Error occurred
    WARNING = "warning"  # Warning raised


class Event(Base):
    """
    Event model for the append-only Event Store.

    Events capture all cognitive activity in the NeuroStack pipeline.
    They are immutable once created and provide:
    - Complete audit trail
    - Analytics data source
    - Training data generation
    - Debugging and troubleshooting

    Attributes:
        id: Unique event identifier (UUID)
        tenant_id: Tenant that generated this event
        session_id: Associated session (optional for system events)
        event_type: Type of event (from EventType enum)
        event_data: JSON payload with event details
        metadata: Additional metadata (timing, source, etc.)
        created_at: Event timestamp

    Relationships:
        tenant: The tenant that owns this event
        session: The session this event belongs to (if applicable)

    Note:
        Events are append-only. They should never be updated or deleted
        in normal operation. Use soft-delete flags in metadata if needed.
    """

    __tablename__ = "events"
    __table_args__ = (
        CheckConstraint(
            "interaction_origin IN ('production', 'simulator', 'unknown')",
            name="ck_events_interaction_origin",
        ),
        Index(
            "idx_events_tenant_origin_type_created",
            "tenant_id",
            "interaction_origin",
            "event_type",
            text("created_at DESC"),
        ),
    )

    # Primary Key
    id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )

    # Foreign Keys
    tenant_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    session_id: Mapped[Optional[UUID]] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("sessions.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )

    # Event Type
    event_type: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
    )

    interaction_origin: Mapped[str] = mapped_column(
        String(20),
        default=InteractionOrigin.UNKNOWN.value,
        server_default=InteractionOrigin.UNKNOWN.value,
        nullable=False,
    )

    # Event Data (JSONB)
    event_data: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
    )

    # Event Metadata (JSONB)
    # Note: Named event_metadata to avoid conflict with SQLAlchemy's reserved 'metadata'
    event_metadata: Mapped[dict[str, Any]] = mapped_column(
        "metadata",  # Column name in DB
        JSONB,
        default=dict,
        nullable=False,
    )

    # Timestamp (immutable)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        index=True,
    )

    # Relationships
    tenant: Mapped["Tenant"] = relationship(
        "Tenant",
        back_populates="events",
    )
    session: Mapped[Optional["Session"]] = relationship(
        "Session",
        back_populates="events",
    )

    @classmethod
    def create_message_event(
        cls,
        tenant_id: UUID,
        session_id: UUID,
        content: str,
        channel: str,
        is_incoming: bool = True,
        user_id: Optional[str] = None,
        metadata: Optional[dict[str, Any]] = None,
    ) -> "Event":
        """
        Factory method to create a message event.

        Args:
            tenant_id: Tenant identifier
            session_id: Session identifier
            content: Message content
            channel: Communication channel
            is_incoming: True for user messages, False for assistant
            user_id: Optional user identifier
            metadata: Additional metadata

        Returns:
            Event instance (not persisted)
        """
        event_type = EventType.MESSAGE_IN if is_incoming else EventType.MESSAGE_OUT
        return cls(
            tenant_id=tenant_id,
            session_id=session_id,
            event_type=event_type.value,
            event_data={
                "content": content,
                "channel": channel,
                "user_id": user_id,
                "role": "user" if is_incoming else "assistant",
            },
            metadata=metadata or {},
        )

    @classmethod
    def create_decision_event(
        cls,
        tenant_id: UUID,
        session_id: UUID,
        decision: dict[str, Any],
        processing_time_ms: Optional[int] = None,
    ) -> "Event":
        """
        Factory method to create an SRM decision event.

        Args:
            tenant_id: Tenant identifier
            session_id: Session identifier
            decision: SRM decision data
            processing_time_ms: Processing time in milliseconds

        Returns:
            Event instance (not persisted)
        """
        return cls(
            tenant_id=tenant_id,
            session_id=session_id,
            event_type=EventType.SRM_DECISION.value,
            event_data=decision,
            metadata={
                "processing_time_ms": processing_time_ms,
            },
        )

    @classmethod
    def create_safety_event(
        cls,
        tenant_id: UUID,
        session_id: UUID,
        safety_category: str,
        confidence: float,
        trigger_content: str,
        action_taken: str,
    ) -> "Event":
        """
        Factory method to create a safety trigger event.

        Args:
            tenant_id: Tenant identifier
            session_id: Session identifier
            safety_category: Category of safety concern
            confidence: Confidence score
            trigger_content: Content that triggered the safety concern
            action_taken: Action taken in response

        Returns:
            Event instance (not persisted)
        """
        return cls(
            tenant_id=tenant_id,
            session_id=session_id,
            event_type=EventType.SAFETY_TRIGGER.value,
            event_data={
                "safety_category": safety_category,
                "confidence": confidence,
                "trigger_content": trigger_content,
                "action_taken": action_taken,
            },
            metadata={},
        )

    @classmethod
    def create_handoff_event(
        cls,
        tenant_id: UUID,
        session_id: UUID,
        reason: str,
        summary: str,
        urgency: str = "normal",
        key_info: Optional[dict[str, Any]] = None,
    ) -> "Event":
        """
        Factory method to create a handoff request event.

        Args:
            tenant_id: Tenant identifier
            session_id: Session identifier
            reason: Reason for handoff
            summary: Conversation summary
            urgency: Urgency level
            key_info: Key information for human agent

        Returns:
            Event instance (not persisted)
        """
        return cls(
            tenant_id=tenant_id,
            session_id=session_id,
            event_type=EventType.HANDOFF_REQUEST.value,
            event_data={
                "reason": reason,
                "summary": summary,
                "urgency": urgency,
                "key_info": key_info or {},
            },
            metadata={},
        )

    @classmethod
    def create_funnel_transition_event(
        cls,
        tenant_id: UUID,
        session_id: UUID,
        from_stage: str,
        to_stage: str,
        trigger_intent: str,
    ) -> "Event":
        """
        Factory method to create a funnel transition event.

        Args:
            tenant_id: Tenant identifier
            session_id: Session identifier
            from_stage: Previous funnel stage
            to_stage: New funnel stage
            trigger_intent: Intent that triggered the transition

        Returns:
            Event instance (not persisted)
        """
        return cls(
            tenant_id=tenant_id,
            session_id=session_id,
            event_type=EventType.FUNNEL_TRANSITION.value,
            event_data={
                "from_stage": from_stage,
                "to_stage": to_stage,
                "trigger_intent": trigger_intent,
            },
            metadata={},
        )

    @property
    def is_message_event(self) -> bool:
        """Check if this is a message event."""
        return self.event_type in (
            EventType.MESSAGE_IN.value,
            EventType.MESSAGE_OUT.value,
        )

    @property
    def is_safety_event(self) -> bool:
        """Check if this is a safety-related event."""
        return self.event_type in (
            EventType.SAFETY_TRIGGER.value,
            EventType.SAFETY_BLOCK.value,
        )

    @property
    def is_handoff_event(self) -> bool:
        """Check if this is a handoff-related event."""
        return self.event_type in (
            EventType.HANDOFF_REQUEST.value,
            EventType.HANDOFF_ACCEPT.value,
            EventType.HANDOFF_COMPLETE.value,
            EventType.HANDOFF_TIMEOUT.value,
            EventType.NS_HANDOFF_CREATED.value,
        )

    def __repr__(self) -> str:
        return f"<Event(id={self.id}, type='{self.event_type}', session={self.session_id})>"
